param(
	[Parameter(Mandatory)] [string]$OutputFile
)

# Writes the panel fonts as C++ byte arrays. The bytes are copied unchanged, so the embedded fonts stay the original
# OFL-licensed files (see fonts\OFL.txt and THIRD-PARTY-NOTICES.txt).
$ErrorActionPreference = 'Stop'

$fonts = [ordered]@{
	regular = Join-Path $PSScriptRoot 'fonts\AtkinsonHyperlegible-Regular.ttf'
	bold = Join-Path $PSScriptRoot 'fonts\AtkinsonHyperlegible-Bold.ttf'
}

$newestInput = ($fonts.Values + $PSCommandPath | ForEach-Object { (Get-Item -LiteralPath $_).LastWriteTimeUtc } | Measure-Object -Maximum).Maximum
if ((Test-Path -LiteralPath $OutputFile) -and (Get-Item -LiteralPath $OutputFile).LastWriteTimeUtc -ge $newestInput) {
	return
}

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('// Generated by embed_fonts.ps1 from tools/reshade-openxr-ui/fonts. Do not edit.')
[void]$builder.AppendLine('namespace vr_ui_fonts')
[void]$builder.AppendLine('{')
foreach ($name in $fonts.Keys) {
	$bytes = [System.IO.File]::ReadAllBytes($fonts[$name])
	[void]$builder.AppendLine("`talignas(4) inline const unsigned char $name[] = {")
	for ($offset = 0; $offset -lt $bytes.Length; $offset += 32) {
		$count = [Math]::Min(32, $bytes.Length - $offset)
		[void]$builder.AppendLine("`t`t0x" + [System.BitConverter]::ToString($bytes, $offset, $count).Replace('-', ',0x') + ',')
	}
	[void]$builder.AppendLine("`t};")
}
[void]$builder.AppendLine('}')

New-Item -ItemType Directory -Path (Split-Path -Parent $OutputFile) -Force | Out-Null
[System.IO.File]::WriteAllText($OutputFile, $builder.ToString())
